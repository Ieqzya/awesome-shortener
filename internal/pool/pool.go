// Package pool предоставляет типобезопасный пул объектов с поддержкой метода Reset().
//
// Пакет реализует generic структуру Pool, которая может хранить объекты любого типа,
// имеющего метод Reset(). Это позволяет переиспользовать объекты и снижать нагрузку
// на сборщик мусора.
//
// # Пример использования
//
//	// Определяем структуру с методом Reset
//	type Request struct {
//		ID   int
//		Data []byte
//	}
//
//	func (r *Request) Reset() {
//		r.ID = 0
//		r.Data = r.Data[:0]
//	}
//
//	// Создаем пул
//	pool := pool.New(func() *Request {
//		return &Request{
//			Data: make([]byte, 0, 1024),
//		}
//	})
//
//	// Получаем объект из пула
//	req := pool.Get()
//	req.ID = 123
//	req.Data = append(req.Data, []byte("data")...)
//
//	// Возвращаем объект в пул (автоматически вызывается Reset)
//	pool.Put(req)
package pool

import "sync"

// Resettable определяет интерфейс для типов, которые могут быть сброшены к начальному состоянию.
//
// Типы, реализующие этот интерфейс, могут использоваться в Pool для автоматической
// очистки перед возвратом в пул.
type Resettable interface {
	// Reset сбрасывает объект к начальному состоянию
	Reset()
}

// Pool представляет типобезопасный пул объектов с поддержкой метода Reset().
//
// Pool использует sync.Pool внутри для эффективного переиспользования объектов
// и автоматически вызывает метод Reset() перед возвратом объекта в пул.
//
// Параметр типа T должен быть указателем на тип, реализующий интерфейс Resettable.
//
// # Пример
//
//	type MyStruct struct {
//		Value int
//	}
//
//	func (m *MyStruct) Reset() {
//		m.Value = 0
//	}
//
//	pool := pool.New(func() *MyStruct {
//		return &MyStruct{}
//	})
//
//	obj := pool.Get()
//	obj.Value = 42
//	pool.Put(obj) // Автоматически вызовет obj.Reset()
type Pool[T Resettable] struct {
	pool sync.Pool
	new  func() T
}

// New создает новый типобезопасный пул объектов.
//
// Функция принимает конструктор, который будет вызываться для создания новых объектов,
// когда пул пуст. Конструктор должен возвращать указатель на объект типа T.
//
// Параметры:
//   - newFunc: функция-конструктор для создания новых объектов
//
// Возвращает указатель на инициализированный Pool.
//
// # Пример
//
//	pool := pool.New(func() *Request {
//		return &Request{
//			Data: make([]byte, 0, 1024), // Предаллоцируем память
//		}
//	})
func New[T Resettable](newFunc func() T) *Pool[T] {
	p := &Pool[T]{
		new: newFunc,
	}

	// Инициализируем sync.Pool с нашим конструктором
	p.pool.New = func() interface{} {
		return newFunc()
	}

	return p
}

// Get извлекает объект из пула или создает новый, если пул пуст.
//
// Если в пуле есть доступные объекты, возвращается один из них.
// Если пул пуст, вызывается функция-конструктор для создания нового объекта.
//
// Возвращает объект типа T, готовый к использованию.
//
// # Пример
//
//	req := pool.Get()
//	req.ID = 123
//	req.Data = append(req.Data, []byte("hello")...)
//	// Используем объект...
//	pool.Put(req) // Не забываем вернуть в пул
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put возвращает объект в пул после автоматического вызова метода Reset().
//
// Метод сначала вызывает Reset() на объекте для очистки его состояния,
// а затем помещает объект обратно в пул для последующего переиспользования.
//
// Параметры:
//   - obj: объект для возврата в пул
//
// # Важно
//
// После вызова Put() не следует использовать переданный объект,
// так как он может быть выдан другой горутине через Get().
//
// # Пример
//
//	req := pool.Get()
//	defer pool.Put(req) // Гарантируем возврат в пул
//
//	req.ID = 123
//	// Работаем с объектом...
//	// После выхода из функции объект будет очищен и возвращен в пул
func (p *Pool[T]) Put(obj T) {
	// Сбрасываем объект перед возвратом в пул
	obj.Reset()

	// Возвращаем в пул
	p.pool.Put(obj)
}
